-- BattleGroup Gun Name Conversion Table
-- Maps full weapon names from bg_builder_weapons to abbreviated datacard display names
-- Created: 2025-11-10
-- Purpose: Provide consistent short names for equipment datacards (space-constrained display)

CREATE TABLE IF NOT EXISTS bg_gun_name_conversion (
    conversion_id INTEGER PRIMARY KEY AUTOINCREMENT,
    weapon_name TEXT NOT NULL UNIQUE,
    datacard_name TEXT NOT NULL,
    created_date TEXT DEFAULT (datetime('now')),
    notes TEXT,
    FOREIGN KEY (weapon_name) REFERENCES bg_builder_weapons(weapon_name)
);

-- Create index for fast lookups during datacard generation
CREATE INDEX IF NOT EXISTS idx_bg_gun_conversion_weapon
ON bg_gun_name_conversion(weapon_name);

